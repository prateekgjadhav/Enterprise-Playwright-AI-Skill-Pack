#!/usr/bin/env node
// Render the routing table from the manifest, so routing is generated from the skills and never kept by hand
// in two places. Diff the output against CLAUDE.md when skills change; check-skills.mjs gates coverage.
// Usage: node scripts/generate-routing.mjs [.agents/skills-manifest.json] > routing.generated.md
import { readFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync(process.argv[2] ?? '.agents/skills-manifest.json', 'utf8'));
const TIERS = {
  1: 'Tier 1: core development',
  2: 'Tier 2: execution and operations',
  3: 'Tier 3: quality engineering, Penetration Testing, risk and posture',
  4: 'Tier 4: governance and meta',
};
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const out = ['<!-- Generated by scripts/generate-routing.mjs from .agents/skills. Do not edit; regenerate it. -->', '# Skill routing', ''];
for (const tier of Object.keys(TIERS)) {
  const rows = manifest.skills.filter((s) => !s.error && String(s.tier) === tier);
  if (!rows.length) continue;
  out.push(`## ${TIERS[tier]}`, '', '| Skill | Use it when the user asks… | Not for |', '|---|---|---|');
  for (const s of rows) out.push(`| \`${s.name}\` | ${cell(s.useWhen)} | ${cell(s.notFor)} |`);
  out.push('');
}
const broken = manifest.skills.filter((s) => s.error || !TIERS[String(s.tier)]);
if (broken.length) {
  out.push('## Not routed: fix these skills', '');
  for (const s of broken) out.push(`- \`${s.folder}\`: ${s.error ?? `unknown tier "${s.tier}"`}`);
  out.push('');
}
process.stdout.write(out.join('\n'));
